//! The Hot Sheet out-of-process plugin protocol (docs/38-plugin-protocol.md, HS2-XY0VTN).
//!
//! A code-bearing plugin is a separate executable. The host starts it, speaks the
//! `$/hello` handshake as one JSON-RPC line, and then both sides use the transport the
//! plugin chose: JSON-RPC 2.0 as newline-delimited JSON, or length-prefixed protobuf
//! frames. Both carry the same contract messages from `proto/`, generated into [`v1`].
//!
//! This crate is synchronous and runtime-free so the host (CLI and server) and plugin
//! authors can both use it: [`wire`] encodes and decodes messages, [`handshake`] runs the
//! hello exchange, and [`serve`] is the plugin-side request loop.

/// Generated contract types (prost) with canonical proto3 JSON serde impls (pbjson).
